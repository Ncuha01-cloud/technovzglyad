<?php

/*
|--------------------------------------------------------------------------
| Настройки приложения (config/app.php)
|--------------------------------------------------------------------------
| Этот файл Laravel читает при каждом запуске.
| Здесь задаются имя сайта, язык, часовой пояс и режим отладки.
| Значения берутся из файла .env, а вторым аргументом указано значение
| по умолчанию — оно используется, если переменная в .env не задана.
*/

return [

    // Название сайта: выводится в шапке, подвале и заголовке вкладки браузера.
    'name' => env('APP_NAME', 'Laravel'),

    // Окружение: local — разработка, production — боевой сервер, testing — тесты.
    'env' => env('APP_ENV', 'production'),

    // Режим отладки: true показывает подробные ошибки, false — общую страницу ошибки.
    'debug' => (bool) env('APP_DEBUG', false),

    // Базовый адрес сайта. Нужен консольным командам для построения ссылок.
    'url' => env('APP_URL', 'http://localhost'),

    // Часовой пояс. Для Москвы в .env указан Europe/Moscow.
    'timezone' => env('APP_TIMEZONE', 'UTC'),

    // Основной язык интерфейса и сообщений (ru — русский).
    'locale' => env('APP_LOCALE', 'en'),

    // Запасной язык, если для основного нет перевода.
    'fallback_locale' => env('APP_FALLBACK_LOCALE', 'en'),

    // Язык генерации тестовых данных библиотекой Faker.
    'faker_locale' => env('APP_FAKER_LOCALE', 'en_US'),

    // Алгоритм шифрования данных приложения.
    'cipher' => 'AES-256-CBC',

    // Ключ шифрования. Генерируется командой php artisan key:generate.
    'key' => env('APP_KEY'),

    // Старые ключи шифрования — нужны при плавной смене APP_KEY.
    'previous_keys' => [
        // Читаем список ключей из .env через запятую и убираем пустые значения.
        ...array_filter(
            explode(',', (string) env('APP_PREVIOUS_KEYS', ''))
        ),
    ],

    // Настройки режима обслуживания (когда сайт временно закрыт).
    'maintenance' => [
        // Драйвер хранения флага обслуживания: file, cache или array.
        'driver' => env('APP_MAINTENANCE_DRIVER', 'file'),

        // Хранилище флага, если выбран драйвер cache.
        'store' => env('APP_MAINTENANCE_STORE', 'database'),
    ],

];

<?php

/*
|--------------------------------------------------------------------------
| Настройки авторизации (config/auth.php)
|--------------------------------------------------------------------------
| Здесь описано, как Laravel проверяет логин и пароль.
| Изменено: вход выполняется по полю login, а не по email.
| Модель пользователя — App\Models\User, пароль хранится в виде хеша.
*/

use App\Models\User;

return [

    // Что используется по умолчанию для входа и восстановления пароля.
    'defaults' => [
        'guard' => env('AUTH_GUARD', 'web'), // Охранник web (сессия браузера).
        'passwords' => env('AUTH_PASSWORD_BROKER', 'users'), // Брокер паролей users.
    ],

    // Охранники (guards) — способы проверки пользователя.
    'guards' => [
        'web' => [
            'driver' => 'session', // Данные входа хранятся в сессии.
            'provider' => 'users', // Пользователи берутся из провайдера users.
        ],
    ],

    // Провайдеры — откуда брать пользователей.
    'providers' => [
        'users' => [
            'driver' => 'eloquent', // Работаем через Eloquent-модель.
            'model' => env('AUTH_MODEL', User::class), // Класс модели пользователя.
        ],

        // Альтернативный вариант: брать пользователей напрямую из таблицы.
        // 'users' => [
        //     'driver' => 'database',
        //     'table' => 'users',
        // ],
    ],

    // Настройки сброса пароля (в проекте не используется).
    'passwords' => [
        'users' => [
            'provider' => 'users', // Провайдер пользователей.
            'table' => env('AUTH_PASSWORD_RESET_TOKEN_TABLE', 'password_reset_tokens'), // Таблица токенов.
            'expire' => 60, // Токен живёт 60 минут.
            'throttle' => 60, // Повторный запрос не чаще раза в 60 секунд.
        ],
    ],

    // Сколько секунд действует подтверждение пароля (по умолчанию 3 часа).
    'password_timeout' => env('AUTH_PASSWORD_TIMEOUT', 10800),

];
